// switch case
const year=3
switch (year) {
    case 1:
        console.log("welcome to january");
        break;
    case 2:
        console.log("welcome to february");
        break;
    case 3:
        console.log("welcome to March");
        break;
    case 4:
        console.log("welcome to April");
        break;
    case 5:
        console.log("welcome to May");
        break;
   

    default:
        console.log("input not valid");
        
        break;
}